"""Writes native/editor/ui_logo.h: the editor's logo for its header (native/editor/assets/editor-logo.png, HellForge's
icon, as the launcher's hellforge-icon.png is), in colour, its dark
backdrop made transparent (each pixel's alpha is how far it stands from the backdrop's colour, its colour
recovered from that blend), cropped to the emblem and box-filtered to UI_LOGO_SIZE square, RGBA.
    py -3 scripts/ui_logo.py"""
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SIZE = 128
SOFT = 48.0  # a channel this far from the backdrop is fully opaque


def read_png(path):
    data = Path(path).read_bytes()
    at, idat = 8, b''
    while at < len(data):
        n, kind = struct.unpack('>I4s', data[at:at + 8])
        body = data[at + 8:at + 8 + n]
        if kind == b'IHDR':
            w, h, depth, colour = struct.unpack('>IIBB', body[:10])
            assert depth == 8 and colour in (2, 6), (depth, colour)
            ch = 3 if colour == 2 else 4
        elif kind == b'IDAT':
            idat += body
        at += 12 + n
    raw = zlib.decompress(idat)
    stride = w * ch
    rows, prev, at = [], bytearray(stride), 0
    for _ in range(h):
        f, line = raw[at], bytearray(raw[at + 1:at + 1 + stride])
        at += 1 + stride
        for i in range(stride):
            a = line[i - ch] if i >= ch else 0
            b, c = prev[i], prev[i - ch] if i >= ch else 0
            if f == 1: line[i] = (line[i] + a) & 255
            elif f == 2: line[i] = (line[i] + b) & 255
            elif f == 3: line[i] = (line[i] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c; pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append(line)
        prev = line
    return w, h, [[tuple(r[x * ch:x * ch + 3]) for x in range(w)] for r in rows]


def main():
    w, h, px = read_png(ROOT / 'native' / 'editor' / 'assets' / 'editor-logo.png')
    bg = px[2][2]
    rgba = []
    for y in range(h):
        row = []
        for x in range(w):
            p = px[y][x]
            a = min(1.0, max(abs(p[i] - bg[i]) for i in range(3)) / SOFT)
            colour = tuple(min(255, max(0, round(bg[i] + (p[i] - bg[i]) / a))) for i in range(3)) if a > 0 else (0, 0, 0)
            row.append(colour + (a,))
        rgba.append(row)
    ys = [y for y in range(h) if any(rgba[y][x][3] > 0.05 for x in range(w))]
    xs = [x for x in range(w) if any(rgba[y][x][3] > 0.05 for y in range(h))]
    side = max(xs[-1] - xs[0], ys[-1] - ys[0]) + 1
    cx, cy = (xs[0] + xs[-1]) // 2, (ys[0] + ys[-1]) // 2
    x0, y0 = cx - side // 2, cy - side // 2
    out = []
    for oy in range(SIZE):
        for ox in range(SIZE):
            sx0, sx1 = x0 + ox * side // SIZE, x0 + (ox + 1) * side // SIZE
            sy0, sy1 = y0 + oy * side // SIZE, y0 + (oy + 1) * side // SIZE
            tot = [0.0, 0.0, 0.0, 0.0]; n = 0
            for sy in range(sy0, max(sy1, sy0 + 1)):
                for sx in range(sx0, max(sx1, sx0 + 1)):
                    if 0 <= sx < w and 0 <= sy < h:
                        r, g, b, a = rgba[sy][sx]
                        tot[0] += r * a; tot[1] += g * a; tot[2] += b * a; tot[3] += a
                    n += 1
            a = tot[3] / n if n else 0
            colour = [round(t / tot[3]) if tot[3] else 0 for t in tot[:3]]
            out += colour + [round(a * 255)]
    lines = ['/* Generated by scripts/ui_logo.py from native/editor/assets/editor-logo.png: the editor\'s logo, %d x %d RGBA,' % (SIZE, SIZE),
             ' * its backdrop transparent. Do not edit. */', '#pragma once', '#define UI_LOGO_SIZE %d' % SIZE,
             'static const unsigned char kUiLogo[UI_LOGO_SIZE * UI_LOGO_SIZE * 4] = {']
    for i in range(0, len(out), 48):
        lines.append('    ' + ','.join(str(v) for v in out[i:i + 48]) + ',')
    lines.append('};')
    (ROOT / 'native' / 'editor' / 'ui_logo.h').write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print('wrote native/editor/ui_logo.h; backdrop', bg, 'emblem', side, 'px; bracket red', px[100][100])


if __name__ == '__main__':
    main()
