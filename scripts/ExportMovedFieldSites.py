#!/usr/bin/env python3
"""The game's own bytes at every site of native/mod-loader/moved_fields.c, for the loader's test.

usage: ExportMovedFieldSites.py <decoded game.dll image> [out header]

The test stages these bytes instead of the table's own, so a site with a wrong address, code or `add` fails it. Run it
on a decoded image of the build moved_fields.c names whenever that table changes.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NUMBER = r'(?:0x[0-9A-Fa-f]+|\d+)'
SITE = re.compile(r'MF_SITE(_BY)?\((MF_\w+), (0x[0-9A-Fa-f]+)u, (\d), %s, ((?(1)%s, )[^)]*)\)' % (NUMBER, NUMBER))


def main():
    image = Path(sys.argv[1]).read_bytes()
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / 'native/mod-loader/test/moved_field_bytes.h'
    rows = []
    for by, field, rva, width, code in SITE.findall((ROOT / 'native/mod-loader/moved_fields.c').read_text()):
        at, size = int(rva, 16), len(code.split(',')) - (1 if by else 0) + int(width)  # MF_SITE_BY's `by` is no code
        rows.append('    {0x%Xu, %d, {%s}}, /* %s */' % (at, size, ', '.join('0x%02x' % b for b in image[at:at + size]), field))
    text = ['/* Generated by scripts/ExportMovedFieldSites.py from a decoded game.dll of build 25480438: the game\'s bytes at',
            ' * every site of moved_fields.c, in the table\'s order. Do not edit. */',
            '#pragma once',
            'typedef struct MfGameBytes { uint32_t rva; uint8_t size; uint8_t bytes[20]; } MfGameBytes;',
            'static const MfGameBytes kMfGameBytes[] = {'] + rows + ['};', '']
    out.write_text('\n'.join(text))
    print('%d sites -> %s' % (len(rows), out))


if __name__ == '__main__':
    main()
