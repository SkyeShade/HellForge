"""Export the enemies' death explosions (mappings/death-explosions.json) for the loader: native/mod-loader/death_explosions.h.

Usage: py scripts/ExportDeathExplosions.py

mappings/death-explosions.json lists, per enemy (the stats files' enemy names), the explosions its behaviour code fires
as it dies: a row id, the vanilla type, and where the game fires it. The header gives the loader each row's id, the
enemy's resource and the vanilla type; BehaviourExplosion's hook swaps that type for the row's (death_explosions.c).
Metadata only: ids, resources, types.
"""
import json
from pathlib import Path

ROOT = Path(__file__).parent.parent


def rows(data):
    out = []
    for name, enemy in data['enemies'].items():
        for r in enemy['rows']:
            out.append((r['id'], int(enemy['resource'], 16), r['explosion'], name, r['label']))
    out.sort()
    if [r[0] for r in out] != list(range(1, len(out) + 1)):
        raise ValueError('death explosion rows must be numbered 1, 2, 3 ... without gaps')
    if len({(r[1], r[2]) for r in out}) != len(out):
        raise ValueError('an enemy lists the same explosion twice')
    return out


def main():
    data = json.loads((ROOT / 'mappings' / 'death-explosions.json').read_text(encoding='utf-8'))
    if data.get('build') != '25480438':
        raise ValueError('death-explosions.json is for another build')
    h = ['/* Generated by scripts/ExportDeathExplosions.py from mappings/death-explosions.json for game build 25480438; do not',
         ' * edit. Included by death_explosions.c: a row id, the enemy\'s entity resource and the explosion type its behaviour',
         ' * fires as it dies. */', '',
         'typedef struct DeathSite { uint32_t id; uint64_t resource; uint32_t type; } DeathSite;',
         'static const DeathSite kDeathSites[] = {']
    for rid, resource, kind, name, label in rows(data):
        h.append(f'    {{{rid}u, 0x{resource:016X}ull, {kind}u}}, /* {name}: {label} */')
    h.append('};')
    (ROOT / 'native' / 'mod-loader' / 'death_explosions.h').write_text('\n'.join(h) + '\n', encoding='utf-8', newline='\n')
    print(f'{len(rows(data))} death explosions of {len(data["enemies"])} enemies')


if __name__ == '__main__':
    main()
