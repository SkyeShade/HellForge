"""Export the sites of the component tables HellForge may grow in place (native/mod-loader/table_growth.c), for the mod
loader: per table, every constant in game.dll that encodes its slot count, with its reviewed instruction bytes, where its
immediate is and how its new value follows from a new slot count; and the rules a new slot count must keep.

Usage: py scripts/ExportTableGrowth.py <growth-sites.json> native/mod-loader/table_growth_sites.h

From the static pass in HD2Mods\\research\\table-growth (extract_priority.py, check_priority.py: build 25480438, the 16
tables weapons and stratagems use). Only tables the pass found growable are written; a table it did not cover, or
refused, stays at its size and its entities are refused as before. The loader checks every instruction's bytes before
it writes anything, so a game build these were not made for grows nothing.
"""
import json
import sys

FORMULAS = {
    'S': 'GROW_S', 'S-1': 'GROW_S_MINUS_1', 'S-1@mask': 'GROW_MASK', '16*S/m': 'GROW_INDEX_SCALED',
    '16*S+(R-1)*stride': 'GROW_DEFAULT_OFFSET', 'magic64(S)': 'GROW_MAGIC', 'shift(S)': 'GROW_SHIFT',
    'magic65(S)': 'GROW_MAGIC65', 'shift65(S)': 'GROW_SHIFT65',
}


def main(source, out):
    data = json.load(open(source, encoding='utf-8'))
    if data.get('build') != '25480438':
        raise SystemExit(f"{source} is for build {data.get('build')}")
    constants, tables = [], []
    for component, t in sorted(data['tables'].items(), key=lambda kv: int(kv[0])):
        if not t['growable']:
            continue
        first = len(constants)
        for site in t['sites']:
            for c in site['constants']:
                code = bytes.fromhex(c['bytes'])
                if len(code) > 15 or c['imm_offset'] + c['imm_size'] > len(code) or c['formula'] not in FORMULAS:
                    raise SystemExit(f"table {component}: {c['rva']} is not a constant the loader can write")
                constants.append((int(c['rva'], 16), len(code), c['imm_offset'], c['imm_size'], FORMULAS[c['formula']],
                                  c.get('divisor', 0), code))
        r = t['rules']
        flags = []
        if 'depends_on' in t:
            flags.append('GROWTH_NEEDS_ARMORY')
        if 'protected_match' in t:
            flags.append('GROWTH_PROTECTED_MATCH')
        tables.append((int(component), ' | '.join(flags) or '0', t['slots'], t['records'], t['stride'],
                       min(r['max_slots'], 0x7FFFFFFF), r['slots_multiple_of'], int(r['pow2']), int(r['magic64']),
                       first, len(constants) - first, t['name']))
    lines = [
        f"/* Generated by scripts/ExportTableGrowth.py from the table-growth pass (build {data['build']}, game.dll SHA-256",
        f" * {data.get('game_dll_sha256') or '?'}); do not edit. The component tables HellForge may grow in place",
        " * (table_growth.c): each constant that encodes a table's slot count, its reviewed instruction and where its immediate is,",
        " * and the rules a new slot count must keep. */",
        "static const GrowthConstant kGrowthConstants[] = {",
    ]
    for rva, length, offset, size, formula, divisor, code in constants:
        body = ', '.join(f'0x{b:02x}' for b in code)
        lines.append(f"    {{0x{rva:X}u, {length}, {offset}, {size}, {formula}, {divisor}u, {{{body}}}}},")
    lines.append("};")
    lines.append("static const GrowthTable kGrowthTables[] = {")
    for (component, flags, slots, records, stride, most, multiple, pow2, magic64, first, count, name) in tables:
        lines.append(f"    {{{component}, {flags}, {slots}u, {records}u, {stride}u, {{{most}u, {multiple}u, {pow2}, {magic64}}}, {first}, {count}}}, /* {name} */")
    lines.append("};")
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    print(f"{len(tables)} tables, {len(constants)} constants -> {out}")


if __name__ == '__main__':
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2])
