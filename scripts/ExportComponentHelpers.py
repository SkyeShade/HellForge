"""Export the component tables whose every game lookup goes through a helper, with those helpers, for the mod loader's
overflow rows (native/mod-loader/component_overflow.c): a full table gets more rows outside its compiled index, and only
a table the game reads through helpers can (the loader hooks them; a lookup inlined elsewhere would never see the row).

Usage: py scripts/ExportComponentHelpers.py <sites.json> native/mod-loader/component_helpers.h

From the component-table site inventory of build 25480438 (research content-limits\\component-tables\\sites.json: every
reference to an entity component table in game.dll's code, classified). A table qualifies when its sites are only
lookup helpers (Get(key), Get(&key)), default-record getters and the default reads right after a helper's call (which
read the default only when the helper found nothing), and loaded checks; table 29's armory iterator is in the builder
the loader replaces (registry_load.c BuildArmory). For each helper: its table, whether it takes the key by pointer, its
RVA and its first 16 bytes (the loader checks them before hooking).
"""
import json
import sys

BENIGN = {'lookup_helper_A', 'lookup_helper_B', 'default_helper_C', 'default_after_call', 'presence_check'}
ALLOWED = {29: {'record_iterator_armory'}}


def main(sites, out):
    inventory = json.loads(open(sites, encoding='utf-8').read())
    helpers = []
    tables = 0
    for key, table in sorted(inventory['tables'].items(), key=lambda kv: int(kv[0])):
        component = int(key)
        classes = {site.get('class') for site in table['sites']}
        if classes - BENIGN - ALLOWED.get(component, set()):
            continue
        found = [(component, site['class'] == 'lookup_helper_B', int(site['helper_start'], 16), site['helper_entry_bytes'])
                 for site in table['sites'] if site['class'] in ('lookup_helper_A', 'lookup_helper_B')]
        if not found:
            continue
        tables += 1
        helpers.extend(found)
    lines = ['/* Generated by scripts/ExportComponentHelpers.py from the component-table site inventory of build 25480438 (game.dll',
             f" * {inventory['game_dll_sha256'][:16]}...); do not edit. The {tables} component tables whose every game lookup goes through a",
             ' * helper, and those helpers: its table, whether it takes the key by pointer (Get(&key)), its RVA and its first 16',
             ' * bytes. */',
             'typedef struct ComponentHelper { uint16_t component; uint8_t byPointer; uint32_t rva; uint8_t pin[16]; } ComponentHelper;',
             'static const ComponentHelper kComponentHelpers[] = {']
    for component, by_pointer, rva, pin in helpers:
        data = ', '.join(f'0x{pin[i:i + 2]}' for i in range(0, 32, 2))
        lines.append(f'    {{{component}, {int(by_pointer)}, 0x{rva:X}u, {{{data}}}}},')
    lines[-1] = lines[-1].rstrip(',')
    lines.append('};')
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    print(f'{tables} tables, {len(helpers)} helpers -> {out}')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
