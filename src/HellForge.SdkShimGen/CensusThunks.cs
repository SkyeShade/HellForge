using System.Text;
using System.Text.RegularExpressions;
using HellForge.SdkShimGen;

// The Steam census's stand-in (docs/steam-bridge.md, step 2): the same exports as Valve's steam_api64.dll, but each
// function the stand-in does not write itself becomes a thunk that counts the call (CensusExport in steam_census.c) and
// jumps to Valve's export, with the argument registers untouched, so no signature is needed. Data exports still forward.
// It also writes the slot thunks of the census's interface proxies: slot k counts the call (CensusSlot, which returns the
// real object's slot k), puts the real interface object in RCX and jumps there.
static class CensusThunks
{
    public const int Slots = 192;

    // The argument registers (RCX, RDX, R8, R9, XMM0-3) are saved around the counting call; entry RSP is 8 mod 16, so
    // four pushes and 0x68 bytes leave it 16-byte aligned at the call, with 0x20 bytes of shadow space below the saves.
    // The prologue carries unwind codes, so a stack walk or exception during the call unwinds through the thunk.
    const string Save = """
          push rcx
          .seh_pushreg rcx
          push rdx
          .seh_pushreg rdx
          push r8
          .seh_pushreg r8
          push r9
          .seh_pushreg r9
          sub rsp, 0x68
          .seh_stackalloc 0x68
          .seh_endprologue
          movdqu xmmword ptr [rsp+0x20], xmm0
          movdqu xmmword ptr [rsp+0x30], xmm1
          movdqu xmmword ptr [rsp+0x40], xmm2
          movdqu xmmword ptr [rsp+0x50], xmm3
        """;
    // The saved RCX, which a slot thunk replaces with the real object before the restore.
    const int SavedRcx = 0x80;
    // An epilog the x64 unwinder recognizes: add rsp, the pops, then a tail jump. "jmp r11" carries REX.W (49 FF E3),
    // the form Windows' unwinder accepts as a tail call that ends an epilog.
    const string Restore = """
          movdqu xmm0, xmmword ptr [rsp+0x20]
          movdqu xmm1, xmmword ptr [rsp+0x30]
          movdqu xmm2, xmmword ptr [rsp+0x40]
          movdqu xmm3, xmmword ptr [rsp+0x50]
          add rsp, 0x68
          pop r9
          pop r8
          pop rdx
          pop rcx
          .byte 0x49, 0xff, 0xe3
          .seh_endproc
        """;

    const int MaxExports = 2048, MaxName = 127;

    public static int Write(string original, string module, string handwritten, string definitionOutput, string codeOutput, Func<string, HashSet<string>> ownFunctions)
    {
        if (!Regex.IsMatch(module, @"^[A-Za-z0-9_]+$")) throw new InvalidDataException("The real module name must be a plain DLL name without extension.");
        var exports = PeTables.Exports(original);
        var own = ownFunctions(handwritten);
        var unknown = own.Where(name => exports.All(e => e.Name != name)).ToList();
        if (unknown.Count > 0) throw new InvalidDataException("Hand-written functions the original does not export: " + string.Join(", ", unknown));
        var data = PeTables.DataExports(original);
        var thunked = exports.Where(e => !own.Contains(e.Name) && !data.Contains(e.Name)).OrderBy(e => e.Ordinal).ToList();
        if (thunked.Any(e => !Regex.IsMatch(e.Name, @"^[A-Za-z_][A-Za-z0-9_]*$"))) throw new InvalidDataException("An export name is not a C identifier.");
        // steam_census.c's tables: CENSUS_EXPORTS thunks, and names short enough for its log keys (CENSUS_KEY)
        if (thunked.Count > MaxExports) throw new InvalidDataException($"{thunked.Count} exports to thunk; steam_census.c holds {MaxExports} (CENSUS_EXPORTS).");
        if (thunked.FirstOrDefault(e => e.Name.Length > MaxName) is { } longName) throw new InvalidDataException($"Export name over {MaxName} characters: {longName.Name}");
        var index = thunked.Select((e, i) => (e.Name, i)).ToDictionary(p => p.Name, p => p.i, StringComparer.Ordinal);

        var definition = new StringBuilder().AppendLine($"LIBRARY {Path.GetFileName(original)}").AppendLine("EXPORTS");
        foreach (var export in exports.OrderBy(e => e.Ordinal))
            definition.AppendLine(
                own.Contains(export.Name) ? $"    {export.Name} @{export.Ordinal}" :
                data.Contains(export.Name) ? $"    {export.Name} = {module}.{export.Name} @{export.Ordinal} DATA" :
                $"    {export.Name} = hf_census_export_{index[export.Name]} @{export.Ordinal}");
        File.WriteAllText(definitionOutput, definition.ToString());

        var code = new StringBuilder();
        code.AppendLine($"// Generated by HellForge.SdkShimGen census-thunks from {Path.GetFileName(original)}: do not edit (CensusThunks.cs).");
        code.AppendLine($"const int g_censusExportCount = {thunked.Count};");
        code.AppendLine($"const char *const g_censusExportNames[{Math.Max(1, thunked.Count)}] = {{");
        foreach (var export in thunked) code.AppendLine($"    \"{export.Name}\",");
        code.AppendLine("};");
        code.AppendLine("__asm__(\".intel_syntax noprefix\\n\"");
        void Line(string text) => code.AppendLine($"    \"{text}\\n\"");
        void Lines(string block) { foreach (var instruction in block.Split('\n')) if (instruction.Trim().Length > 0) Line(instruction.Trim()); }
        void Begin(string name)
        {
            Line(".text");
            Line(".p2align 4");
            Line($".globl {name}");
            Line($".def {name}; .scl 2; .type 32; .endef");
            Line($".seh_proc {name}");
            Line($"{name}:");
            Lines(Save);
        }
        for (var i = 0; i < thunked.Count; i++)
        {
            Begin($"hf_census_export_{i}");
            Line($"mov ecx, {i}");
            Line("call CensusExport");
            Line("mov r11, rax");
            Lines(Restore);
        }
        for (var slot = 0; slot < Slots; slot++)
        {
            Begin($"hf_census_slot_{slot}");
            Line($"mov edx, {slot}");
            Line("call CensusSlot");
            Line("mov r11, rax");
            Line($"mov rcx, qword ptr [rsp+0x{SavedRcx:x}]");
            Line("mov rcx, qword ptr [rcx+8]");
            Line($"mov qword ptr [rsp+0x{SavedRcx:x}], rcx");
            Lines(Restore);
        }
        code.AppendLine("    \".att_syntax\\n\");");
        for (var slot = 0; slot < Slots; slot++) code.AppendLine($"void hf_census_slot_{slot}(void);");
        code.AppendLine($"void *const g_censusSlots[{Slots}] = {{");
        for (var slot = 0; slot < Slots; slot++) code.AppendLine($"    (void *)hf_census_slot_{slot},");
        code.AppendLine("};");
        File.WriteAllText(codeOutput, code.ToString());
        Console.WriteLine($"{Path.GetFileName(original)}: {exports.Count} exports, {own.Count} hand-written, {data.Count} data forwarded, {thunked.Count} census thunks, {Slots} slot thunks.");
        return 0;
    }
}
