/* What the step relies on: the service, the ring's layout, the disposal step it copies (its tables, mask 5, the
 * handle buffer's counts, byte +0x38), the pose sync's layout, an entity record's unit, and the engine's five calls. */
static const CfPin kCfPins[] = {
    {0, 0x13F2A6Bu, sizeof kCfServiceSet, kCfServiceSet}, {0, 0x13BE690u, sizeof kCfRingBase, kCfRingBase},
    {0, 0x13BE6B0u, sizeof kCfRingEntry, kCfRingEntry}, {0, 0x13BE829u, sizeof kCfRingNext, kCfRingNext},
    {0, 0x13BE930u, sizeof kCfSettleTest, kCfSettleTest}, {0, 0x13BE9C3u, sizeof kCfFreezeCalls, kCfFreezeCalls},
    {0, CF_SETTLED, sizeof kCfSettled, kCfSettled}, {0, 0x7AAB38u, sizeof kCfPoseCount, kCfPoseCount},
    {0, 0x7AABC0u, sizeof kCfPoseEntry, kCfPoseEntry}, {0, 0x13C01C7u, sizeof kCfEntityUnit, kCfEntityUnit},
    {1, 0x1FEEB0u, sizeof kCfAlive, kCfAlive}, {1, 0x1FD190u, sizeof kCfPosition, kCfPosition},
    {1, 0x7E1C20u, sizeof kCfHandles, kCfHandles}, {1, 0x7E1F3Du, sizeof kCfHandlesEnd, kCfHandlesEnd},
    {1, 0x77F4F0u, sizeof kCfActors, kCfActors}, {1, 0x7A3D00u, sizeof kCfLevel, kCfLevel}};
#define CF_PINS (sizeof kCfPins / sizeof kCfPins[0])

typedef int (*CfHandlesFn)(uint32_t unit, uint32_t mask, uint8_t* out);
typedef uint8_t (*CfAliveFn)(uint32_t unit);
typedef const float* (*CfPositionFn)(uint32_t unit, int node);
typedef void (*CfIdsFn)(const uint32_t* ids, uint32_t count, int value);
typedef struct CfSlot { uint32_t unit; int have, done; float last[3]; ULONGLONG at; } CfSlot;

static struct
{
    volatile LONG state; /* 0 waiting for the code, 1 on, -1 off; set last, so the game thread sees the rest */
    uintptr_t game, exe;
    int bound;
    CfHandlesFn handles; CfAliveFn alive; CfPositionFn position; CfIdsFn actors, level;
    float settled;
    CfSlot slot[CF_RING];
    volatile LONG frozen, posed;
    LONG frozenReported, posedReported;
    ULONGLONG firstTry, reportedAt;
} g_cf;

static int CfPinned(uintptr_t game, uintptr_t exe)
{
    for (size_t i = 0; i < CF_PINS; i++)
        if (!PinMatches((kCfPins[i].exe ? exe : game) + kCfPins[i].rva, kCfPins[i].bytes, kCfPins[i].length)) return 0;
    return 1;
}

/* The engine's calls through game.dll's own tables, as the disposal step makes them. 0 while a table is still empty;
 * one that holds another address turns the freeze off. */
static int CfBind(void)
{
    uintptr_t game = g_cf.game, exe = g_cf.exe, t[4] = {0}, scene = 0, f[5] = {0};
    if (SafeRead(game + CF_UNIT_API, &t[0], 8) || SafeRead(game + CF_ENGINE_API, &t[1], 8) || SafeRead(game + CF_ACTOR_API, &t[2], 8) ||
        SafeRead(game + CF_RAGDOLL_API, &t[3], 8) || !t[0] || !t[1] || !t[2] || !t[3] || SafeRead(t[1] + 0x18, &scene, 8) || !scene)
        return 0;
    if (SafeRead(t[0], &f[0], 8) || SafeRead(scene + 0x720, &f[1], 8) || SafeRead(scene + 0x88, &f[2], 8) || SafeRead(t[2] + 0x08, &f[3], 8) ||
        SafeRead(t[3] + 0x48, &f[4], 8) || SafeRead(game + CF_SETTLED, &g_cf.settled, 4))
        return 0;
    if (f[0] != exe + 0x7E1C20u || f[1] != exe + 0x1FEEB0u || f[2] != exe + 0x1FD190u || f[3] != exe + 0x77F4F0u || f[4] != exe + 0x7A3D00u)
    {
        g_cf.state = -1;
        Note("corpse freeze: off; the engine's tables are not the reviewed ones");
        return 0;
    }
    g_cf.handles = (CfHandlesFn)f[0]; g_cf.alive = (CfAliveFn)f[1]; g_cf.position = (CfPositionFn)f[2];
    g_cf.actors = (CfIdsFn)f[3]; g_cf.level = (CfIdsFn)f[4];
    return g_cf.bound = 1;
}

/* 1 while the pose sync still moves the unit (its old entity, on a client, until that entity is gone): the disposal
 * step meets only corpses past it. An unreadable manager counts as moving. */
static int CfPosed(uint32_t unit)
{
    uintptr_t m = 0, entities = 0, runtime = 0;
    uint32_t count = 0;
    if (SafeRead(g_cf.game + CF_POSE_SYNC, &m, 8) || m == 0) return 0;
    if (SafeRead(m + 0x10, &count, 4) || SafeRead(m + 0x38, &entities, 8) || SafeRead(m + 0x48, &runtime, 8) || count > CF_POSE_MAX) return 1;
    for (uint32_t i = 0; i < count; i++)
    {
        uintptr_t entity = 0;
        uint32_t of = 0;
        uint8_t on = 0;
        if (SafeRead(entities + 8 * (uintptr_t)i, &entity, 8)) return 1;
        if (entity == 0) continue;
        if (SafeRead(entity + 0xC, &of, 4)) return 1;
        if (of == unit && (SafeRead(runtime + 0x2BB8 * (uintptr_t)i + 0x2BA4, &on, 1) || on)) return 1;
    }
    return 0;
}

/* The disposal step's two calls (game.dll 0x13BE9C7-0x13BE9FF): actors off unless the entry's byte +0x38 keeps them,
 * then ragdoll level 3. The handle getter writes up to +0x5C. */
static int CfFreeze(uint32_t unit, uint8_t keepActors)
{
    uint8_t h[0x60] = {0};
    uint64_t actors, ragdolls;
    uint32_t actorCount, ragdollCount;
    if (g_cf.handles(unit, 5, h) <= 0) return 0;
    memcpy(&actors, h, 8); memcpy(&actorCount, h + 0x38, 4); memcpy(&ragdolls, h + 0x10, 8); memcpy(&ragdollCount, h + 0x40, 4);
    if (!keepActors && actors && actorCount) g_cf.actors((const uint32_t*)(uintptr_t)actors, actorCount, 0);
    if (ragdolls && ragdollCount) g_cf.level((const uint32_t*)(uintptr_t)ragdolls, ragdollCount, 3);
    return 1;
}

/* One ring entry (+0 unit, +8 state, +0x38 the actor byte). State 2 is a Corpse; the game clears an entry whose unit is
 * gone, but only on its own update, so the unit is asked again here before any call. Once a second, as disposal. */
static void CfSlotTick(CfSlot* s, const uint8_t* entry, ULONGLONG now)
{
    uint32_t unit, state;
    memcpy(&unit, entry, 4); memcpy(&state, entry + 8, 4);
    if (unit == 0 || state != 2) { s->unit = 0; return; }
    if (s->unit != unit) { memset(s, 0, sizeof *s); s->unit = unit; }
    if (s->done || now - s->at < 1000 || !g_cf.alive(unit)) return;
    s->at = now;
    const float* p = g_cf.position(unit, 0);
    float dx = p[0] - s->last[0], dy = p[1] - s->last[1], dz = p[2] - s->last[2];
    int settled = s->have && dx * dx + dy * dy + dz * dz < g_cf.settled;
    memcpy(s->last, p, sizeof s->last);
    s->have = 1;
    if (!settled) return;
    if (CfPosed(unit)) { InterlockedIncrement(&g_cf.posed); return; }
    if (CfFreeze(unit, entry[0x38])) { s->done = 1; InterlockedIncrement(&g_cf.frozen); }
}

static void CfFrame(ULONGLONG now)
{
    uintptr_t service = 0;
    uint8_t entry[CF_ENTRY];
    if (!g_cf.bound && !CfBind()) return;
    if (SafeRead(g_cf.game + CF_SERVICE, &service, 8) || service == 0) return;
    for (int i = 0; i < CF_RING; i++)
    {
        if (SafeRead(service + 0x18 + CF_ENTRY * (uintptr_t)i, entry, sizeof entry)) return;
        CfSlotTick(&g_cf.slot[i], entry, now);
    }
}

/* The game thread's update (packages.c TickDetour), after the game's own corpse update in the same frame. */
static void PerfCorpseFreezeTick(void)
{
    if (g_cf.state == 1) CfFrame(GetTickCount64());
}

static void CfInstallAt(uintptr_t game, uintptr_t exe)
{
    if (!PerfFixOn("corpse-freeze")) { g_cf.state = -1; return; }
    g_cf.game = game;
    g_cf.exe = exe;
    InterlockedExchange(&g_cf.state, 1);
    Note("corpse freeze: on; settled corpses in the corpse ring leave the physics world, as in the game's disposal");
}

/* The watch loop, after the game loaded and the game thread's update is hooked; a minute later the code never will be
 * the reviewed one. */
static void PerfCorpseFreezeInstall(void)
{
    if (g_cf.state != 0 || g_tickState == 0) return;
    if (strcmp(g_build, "25480438") || g_tickState < 0)
    {
        g_cf.state = -1;
        Note("corpse freeze: off; %s", g_tickState < 0 ? "the game thread's update is not hooked" : "not this game build");
        return;
    }
    uintptr_t game = ApiModuleBase("game.dll", NULL), exe = (uintptr_t)GetModuleHandleW(NULL);
    if (game != 0 && CfPinned(game, exe)) { CfInstallAt(game, exe); return; }
    if (!g_cf.firstTry) g_cf.firstTry = GetTickCount64();
    if (GetTickCount64() - g_cf.firstTry < 60000) return;
    g_cf.state = -1;
    Note("corpse freeze: off; the corpse ring's code is not the reviewed one");
}

/* What it froze, at most once a minute. */
static void PerfCorpseFreezeWatch(void)
{
    PerfCorpseFreezeInstall();
    if (g_cf.state != 1 || GetTickCount64() - g_cf.reportedAt < 60000) return;
    LONG frozen = g_cf.frozen, posed = g_cf.posed;
    if (frozen == g_cf.frozenReported && posed == g_cf.posedReported) return;
    g_cf.reportedAt = GetTickCount64();
    g_cf.frozenReported = frozen;
    g_cf.posedReported = posed;
    Note("corpse freeze: %ld settled corpse(s) frozen so far; %ld check(s) waited for a pose sync", (long)frozen, (long)posed);
}
