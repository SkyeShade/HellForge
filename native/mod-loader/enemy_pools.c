#define EB_PINS (sizeof kEbPins / sizeof kEbPins[0])

typedef void (*EbPassFn)(uintptr_t component);

static void* volatile g_ebNext;
static uint8_t* g_ebBatch;       /* ours: +0 count, +4 navmesh, entries from +8 */
static uint32_t g_ebCapacity;
static uintptr_t g_ebGame;
static uintptr_t g_ebWorld;      /* the world's batch the component was last pointed away from */
static int g_ebState;            /* 0 waiting for the code, 1 installed, -1 not */
static ULONGLONG g_ebFirstTry, g_ebReportedAt;
static volatile LONG g_ebMost, g_ebMostReported, g_ebShort, g_ebShortReported, g_ebOther;

/* The first pin that differs, or NULL. */
static const char* EdgeBatchMismatch(uintptr_t game)
{
    for (size_t i = 0; i < EB_PINS; i++)
        if (!PinMatches(game + kEbPins[i].rva, kEbPins[i].bytes, kEbPins[i].size)) return kEbPins[i].what;
    return NULL;
}

/* Instances from `from` on get no query this frame: their index 0 tells the clip to skip their edges, as for an agent
 * without one. Only when even our batch is full. */
static void EdgeBatchSkip(uintptr_t component, uint32_t from, uint32_t count)
{
    uintptr_t records = *(uintptr_t*)(component + EB_COMPONENT_RECORDS);
    for (uint32_t i = from; i < count; i++)
    {
        uint32_t handle = *(uint32_t*)(records + (uintptr_t)i * 0xA4u + 0x54u);
        if (handle == 0xFFFFFFFFu) continue;
        uintptr_t block = component + (((uintptr_t)(handle >> 16) - 1u) * 0x486u + 3u + (handle & 0xFFFFu)) * 8u;
        *(uint32_t*)(block + 4) = 0;
    }
}

/* The pass on the game thread. The component's batch and the job's pointer name the same batch while the world set
 * them up; anything else (another world kind's pass, a mod's batch) is left to the game. */
static void EdgeBatchPass(uintptr_t component)
{
    EbPassFn next = (EbPassFn)g_ebNext;
    uintptr_t* mine = (uintptr_t*)(component + EB_COMPONENT_BATCH);
    uintptr_t* shared = (uintptr_t*)(g_ebGame + EB_POINTER);
    uintptr_t ours = (uintptr_t)g_ebBatch;
    if (*mine != ours && *mine != 0 && *mine == *shared) g_ebWorld = *mine; /* a world's own set-up */
    else if (*mine != ours) { InterlockedIncrement(&g_ebOther); next(component); return; }
    /* The pointer goes to 0 when the world is torn down: then nothing reads this frame's queries. */
    uint32_t* world = *shared == ours || *shared == g_ebWorld ? (uint32_t*)g_ebWorld : NULL;
    uint32_t* batch = (uint32_t*)g_ebBatch;
    *mine = ours;
    if (world != NULL)
    {
        *shared = ours;
        batch[0] = world[0];
        batch[1] = world[1];
    }
    else batch[0] = 0;
    uint32_t count = *(volatile uint32_t*)(component + EB_COMPONENT_COUNT);
    uint32_t room = batch[0] < g_ebCapacity ? g_ebCapacity - batch[0] : 0;
    if (count > room)
    {
        InterlockedIncrement(&g_ebShort);
        *(volatile uint32_t*)(component + EB_COMPONENT_COUNT) = room;
        next(component);
        *(volatile uint32_t*)(component + EB_COMPONENT_COUNT) = count;
        EdgeBatchSkip(component, room, count);
    }
    else next(component);
    if (world != NULL) world[0] = batch[0];
    if ((LONG)batch[0] > g_ebMost) g_ebMost = (LONG)batch[0];
}

/* 1 installed, -1 not, 0 not yet: code still being decoded gets until lastTry. */
static int EdgeBatchTry(uintptr_t game, int lastTry)
{
    const char* differs = EdgeBatchMismatch(game);
    if (differs != NULL)
    {
        if (!lastTry) return 0;
        Note("performance fix edge-batch: not installed; %s is not the reviewed code", differs);
        return -1;
    }
    if (!PerfFixOn("edge-batch")) return -1;
    g_ebBatch = (uint8_t*)VirtualAlloc(NULL, 8 + (size_t)EB_CAPACITY * EB_STRIDE, MEM_RESERVE | MEM_COMMIT, PAGE_READWRITE);
    if (g_ebBatch == NULL) { Note("performance fix edge-batch: not installed; no memory for its batch"); return -1; }
    g_ebCapacity = EB_CAPACITY;
    g_ebGame = game;
    if (LoaderHook("edge-batch: the edge pass", game + EB_PASS, (void*)EdgeBatchPass, (void**)&g_ebNext) != 0)
    {
        VirtualFree(g_ebBatch, 0, MEM_RELEASE);
        g_ebBatch = NULL;
        Note("performance fix edge-batch: not installed; the edge pass could not be hooked");
        return -1;
    }
    Note("performance fix edge-batch: installed; the AI's navmesh edge queries have room for %u agents (the game's %u)",
        EB_CAPACITY, EB_GAME_ROOM);
    return 1;
}

/* After the game loaded (WatchStats). A minute later the code never will be the reviewed one. */
static void EdgeBatchWatch(void)
{
    if (g_ebState == 1 && GetTickCount64() - g_ebReportedAt >= 60000 &&
        ((g_ebMost > (LONG)EB_GAME_ROOM && g_ebMost != g_ebMostReported) || g_ebShort != g_ebShortReported))
    {
        g_ebReportedAt = GetTickCount64();
        g_ebMostReported = g_ebMost;
        g_ebShortReported = g_ebShort;
        Note("performance fix edge-batch: up to %ld queries a frame so far (the game held %u)%s", (long)g_ebMostReported,
            EB_GAME_ROOM, g_ebShortReported ? "; some frames had more agents than room, the rest went without edges" : "");
    }
    if (g_ebState != 0) return;
    if (strcmp(g_build, "25480438"))
    {
        g_ebState = -1;
        Note("performance fix edge-batch: not installed; build %s is not the reviewed 25480438", g_build);
        return;
    }
    uintptr_t game = ApiModuleBase("game.dll", NULL);
    if (game == 0) return;
    if (g_ebFirstTry == 0) g_ebFirstTry = GetTickCount64();
    g_ebState = EdgeBatchTry(game, GetTickCount64() - g_ebFirstTry >= 60000);
}
