static uint64_t g_psRandom = 0x9E3779B97F4A7C15ull;
static uint32_t PsRandom(void)
{
    g_psRandom ^= g_psRandom << 13; g_psRandom ^= g_psRandom >> 7; g_psRandom ^= g_psRandom << 17;
    return (uint32_t)(g_psRandom >> 16);
}

static float PsBits(uint32_t bits) { float f; memcpy(&f, &bits, 4); return f; }

/* Record i: x tags it, so a tie that ends in another order shows in the bytes. */
static void PsRecordAt(uint8_t* a, size_t i, float y, float d)
{
    float x = (float)i;
    memcpy(a + i * PS_RECORD, &x, 4);
    memcpy(a + i * PS_RECORD + 4, &y, 4);
    memcpy(a + i * PS_RECORD + 8, &d, 4);
}

/* A key of kind `kind` for record i of n. */
static float PsKeyOf(int kind, size_t i, size_t n)
{
    static const uint32_t odd[] = {0x7FC00000u, 0xFFC00000u, 0x7FC00001u, 0x80000000u, 0x00000000u, 0x7F800000u, 0xFF800000u,
        0x00000001u, 0x3F800000u, 0xBF800000u};
    switch (kind)
    {
    case 0: return (float)(PsRandom() % 10000000u) * 0.37f;           /* random */
    case 1: return (float)(PsRandom() % 4u);                           /* few distinct */
    case 2: return 7.0f;                                               /* all equal */
    case 3: return (float)(i / 3);                                     /* sorted, runs of three */
    case 4: return (float)(n - i);                                     /* reversed */
    case 5: return PsRandom() % 4u ? (float)(PsRandom() % 50u) : PsBits(odd[PsRandom() % 3u]); /* NaN among values */
    case 6: return PsBits(odd[PsRandom() % (sizeof odd / sizeof odd[0])]); /* NaN, signed zeros, infinities, a denormal */
    default: return PsBits(0x7FC00000u);                               /* all NaN */
    }
}

/* Both sorts on one input of n records; their bytes must match. */
static void PsCompare(PsSortFn game, int (*compare)(const void*, const void*), uint8_t* a, uint8_t* b, size_t n, const char* what)
{
    memcpy(b, a, n * PS_RECORD);
    game(a, n, PS_RECORD, compare);
    PsSortRecords(b, n);
    if (memcmp(a, b, n * PS_RECORD) != 0) { printf("FAIL spread sort: %s, %u records\n", what, (unsigned)n); assert(0); }
}

static void PerfSpreadSortFixture(void)
{
    uint8_t* image = (uint8_t*)VirtualAlloc(NULL, PS_IMAGE, MEM_RESERVE, PAGE_NOACCESS);
    assert(image != NULL);
    const uint32_t pages[] = {PS_SORT, PS_COMPARE, PS_COOKIE_CHECK, PS_MEMMOVE, PS_COOKIE};
    for (int i = 0; i < 5; i++) assert(VirtualAlloc(image + (pages[i] & ~0xFFFu), 0x2000, MEM_COMMIT, PAGE_EXECUTE_READWRITE) != NULL);
    uintptr_t game = (uintptr_t)image;
    memcpy(image + PS_SORT, kPsGameSort, sizeof kPsGameSort);
    memcpy(image + PS_COMPARE, kPsComparePin, sizeof kPsComparePin);
    /* the CRT's stand-ins: memmove(rcx, rdx, r8) with rdi and rsi kept; the cookie check passes */
    static const uint8_t move[] = {0x57, 0x56, 0x48,0x89,0xc8, 0x48,0x89,0xcf, 0x48,0x89,0xd6, 0x4c,0x89,0xc1, 0xf3,0xa4, 0x5e, 0x5f, 0xc3};
    memcpy(image + PS_MEMMOVE, move, sizeof move);
    image[PS_COOKIE_CHECK] = 0xc3;
    uint64_t cookie = 0x2B992DDFA232ull;
    memcpy(image + PS_COOKIE, &cookie, 8);
    FlushInstructionCache(GetCurrentProcess(), image, PS_IMAGE);
    PsSortFn gameSort = (PsSortFn)(void*)(image + PS_SORT);
    int (*compare)(const void*, const void*) = (int (*)(const void*, const void*))(void*)(image + PS_COMPARE);

    assert(PsPinned(game));
    image[PS_SORT + 0x200] ^= 1;
    assert(!PsPinned(game)); /* another build's sort is left alone */
    image[PS_SORT + 0x200] ^= 1;
    image[PS_COMPARE + 13] ^= 1;
    assert(!PsPinned(game));
    image[PS_COMPARE + 13] ^= 1;

    size_t most = 460000;
    uint8_t* a = (uint8_t*)VirtualAlloc(NULL, most * PS_RECORD, MEM_RESERVE | MEM_COMMIT, PAGE_READWRITE);
    uint8_t* b = (uint8_t*)VirtualAlloc(NULL, most * PS_RECORD, MEM_RESERVE | MEM_COMMIT, PAGE_READWRITE);
    assert(a != NULL && b != NULL);
    char what[64];
    for (int kind = 0; kind < 8; kind++)
    {
        for (size_t n = 0; n <= 300; n++)
            for (int round = 0; round < (n < 40 ? 8 : 2); round++)
            {
                for (size_t i = 0; i < n; i++) PsRecordAt(a, i, (float)PsRandom(), PsKeyOf(kind, i, n));
                snprintf(what, sizeof what, "key kind %d", kind);
                PsCompare(gameSort, compare, a, b, n, what);
            }
        for (int round = 0; round < 20; round++)
        {
            size_t n = 301 + PsRandom() % (kind >= 5 ? 1500u : 12000u);
            for (size_t i = 0; i < n; i++) PsRecordAt(a, i, (float)PsRandom(), PsKeyOf(kind, i, n));
            snprintf(what, sizeof what, "key kind %d", kind);
            PsCompare(gameSort, compare, a, b, n, what);
        }
    }

    /* SpreadLocations: one list, each location's squared distances written over the last order. Grid points give exact
     * ties; a normal map's ~7k and an extra large map's ~460k random points give float ties. */
    const size_t sizes[] = {2500, 7200, most};
    for (int s = 0; s < 3; s++)
    {
        size_t n = sizes[s];
        float span = s == 2 ? 15500.0f : 2000.0f;
        for (size_t i = 0; i < n; i++)
        {
            float x = s == 0 ? (float)(i % 50) * 16.0f : (float)(PsRandom() % 1000000u) * span / 1000000.0f;
            float y = s == 0 ? (float)(i / 50) * 16.0f : (float)(PsRandom() % 1000000u) * span / 1000000.0f;
            memcpy(a + i * PS_RECORD, &x, 4); memcpy(a + i * PS_RECORD + 4, &y, 4);
        }
        memcpy(b, a, n * PS_RECORD);
        for (int location = 0; location < (s == 2 ? 2 : 12); location++)
        {
            float c[2] = {s == 0 ? 400.0f : (float)(PsRandom() % 1000u) * span / 1000.0f, s == 0 ? 400.0f : (float)(PsRandom() % 1000u) * span / 1000.0f};
            for (size_t i = 0; i < n; i++)
                for (int copy = 0; copy < 2; copy++)
                {
                    uint8_t* r = (copy ? b : a) + i * PS_RECORD;
                    float x, y, d;
                    memcpy(&x, r, 4); memcpy(&y, r + 4, 4);
                    d = (c[0] - x) * (c[0] - x) + (c[1] - y) * (c[1] - y);
                    memcpy(r + 8, &d, 4);
                }
            gameSort(a, n, PS_RECORD, compare);
            PsSortRecords(b, n);
            if (memcmp(a, b, n * PS_RECORD) != 0) { printf("FAIL spread sort: SpreadLocations' list of %u, location %d\n", (unsigned)n, location); assert(0); }
        }
    }

    /* HELLFORGE_PERF_OFF leaves the sort unhooked; then the hook takes only the 12-byte sort by that comparator */
    SetEnvironmentVariableW(L"HELLFORGE_PERF_OFF", L"spread-sort");
    assert(!PerfSpreadSortInstallAt(game) && g_psOriginal == NULL && image[PS_SORT] == 0x48);
    SetEnvironmentVariableW(L"HELLFORGE_PERF_OFF", NULL);
    assert(PerfSpreadSortInstallAt(game) && g_psOriginal != NULL && image[PS_SORT] != 0x48);
    assert(PsPinned(game)); /* read through the hook */
    size_t n = 5000;
    for (size_t i = 0; i < n; i++) PsRecordAt(a, i, 1.0f, (float)(PsRandom() % 64u));
    memcpy(b, a, n * PS_RECORD);
    LONG sorts = g_psSorts;
    gameSort(a, n, PS_RECORD, compare);
    assert(g_psSorts == sorts + 1);
    g_psOriginal(b, n, PS_RECORD, compare); /* the game's own behind the hook; its recursion comes back through it */
    assert(memcmp(a, b, n * PS_RECORD) == 0);
    sorts = g_psSorts;
    int (*other)(const void*, const void*) = (int (*)(const void*, const void*))(void*)(image + PS_COMPARE + 0x40);
    memcpy(image + PS_COMPARE + 0x40, kPsComparePin, sizeof kPsComparePin); /* the same test at another address */
    FlushInstructionCache(GetCurrentProcess(), image + PS_COMPARE + 0x40, sizeof kPsComparePin);
    for (size_t i = 0; i < n; i++) PsRecordAt(a, i, 2.0f, (float)(PsRandom() % 64u));
    memcpy(b, a, n * PS_RECORD);
    gameSort(a, n, PS_RECORD, other);
    assert(g_psSorts == sorts); /* another comparator goes on to the game's sort */
    PsSortRecords(b, n);
    assert(memcmp(a, b, n * PS_RECORD) == 0);
    gameSort(a, n / 2, 24, compare);
    assert(g_psSorts == sorts); /* so does another record size */
    VirtualFree(a, 0, MEM_RELEASE);
    VirtualFree(b, 0, MEM_RELEASE);
    puts("PASS spread sort: the pins, the game's own sort and the replica byte for byte on random, few distinct, equal, sorted, reversed, NaN, signed zero and infinity keys at every size to 300 and beyond, SpreadLocations' repeated sorts with grid and float ties, HELLFORGE_PERF_OFF, other comparators and record sizes left to the game's sort");
}
