typedef void* (*VbBoxFn)(void* out, uint32_t unit, uint32_t flag);
typedef void (*VbPassFn)(void* unused, uint32_t start, uint32_t end, float dt);
typedef struct VbEntry { uint32_t unit; uint8_t box[VB_BYTES]; } VbEntry;

/* The copies live only inside one pass on its own thread: the first entry takes the owner, the copies are dropped at
 * the pass's start and end, and a pass on another thread runs without them. */
static struct
{
    volatile LONG owner; /* the thread inside a pass, 0 none */
    LONG depth;
    uint32_t count;
    VbEntry e[VB_MAX];
} g_vb;
static void* volatile g_vbBoxNext;
static void* volatile g_vbMotionNext;
static void* volatile g_vbSteerNext;
static uintptr_t g_vbSiteReturn;
static LONG64 g_vbCopied; /* written by the owner only */
static int g_vbState;     /* 0 waiting for the code, 1 installed, -1 not */
static ULONGLONG g_vbFirstTry;

static int VbPinned(uintptr_t exe, uintptr_t game)
{
    return exe != 0 && game != 0 && PinMatches(exe + VB_BOX, kVbBoxPin, sizeof kVbBoxPin) &&
        PinMatches(game + VB_SITE, kVbSitePin, sizeof kVbSitePin) && PinMatches(game + VB_MOTION, kVbMotionPin, sizeof kVbMotionPin) &&
        PinMatches(game + VB_STEER, kVbSteerPin, sizeof kVbSteerPin);
}

/* Entered by the hook's jump, so the return address is the caller's. Only the clip's call, with flag 1, on the thread
 * inside a pass, uses the copies; the original returns out. */
static __attribute__((noinline)) void* VbBox(void* out, uint32_t unit, uint32_t flag)
{
    VbBoxFn next = (VbBoxFn)g_vbBoxNext;
    if ((uintptr_t)__builtin_return_address(0) != g_vbSiteReturn || flag != 1 || g_vb.owner != (LONG)GetCurrentThreadId() || g_vb.depth == 0)
        return next(out, unit, flag);
    for (uint32_t i = 0; i < g_vb.count; i++)
        if (g_vb.e[i].unit == unit)
        {
            memcpy(out, g_vb.e[i].box, VB_BYTES);
            g_vbCopied++;
            return out;
        }
    void* r = next(out, unit, flag);
    if (r == out && g_vb.count < VB_MAX)
    {
        g_vb.e[g_vb.count].unit = unit;
        memcpy(g_vb.e[g_vb.count++].box, out, VB_BYTES);
    }
    return r;
}

static void VbPass(void* volatile* next, void* unused, uint32_t start, uint32_t end, float dt)
{
    LONG self = (LONG)GetCurrentThreadId(), was = InterlockedCompareExchange(&g_vb.owner, self, 0);
    if (was != 0 && was != self) { ((VbPassFn)*next)(unused, start, end, dt); return; }
    g_vb.depth++;
    g_vb.count = 0;
    ((VbPassFn)*next)(unused, start, end, dt);
    g_vb.count = 0;
    if (--g_vb.depth == 0) InterlockedExchange(&g_vb.owner, 0);
}

static void VbMotion(void* unused, uint32_t start, uint32_t end, float dt) { VbPass(&g_vbMotionNext, unused, start, end, dt); }
static void VbSteer(void* unused, uint32_t start, uint32_t end, float dt) { VbPass(&g_vbSteerNext, unused, start, end, dt); }

/* Both passes' hooks, then the box's: without the passes the box's hook copies nothing. All three or none. */
static int VehicleBoxInstallAt(uintptr_t exe, uintptr_t game)
{
    g_vbSiteReturn = game + VB_SITE_RETURN;
    int motion = LoaderHook("vehicle boxes: the motion pass", game + VB_MOTION, (void*)VbMotion, (void**)&g_vbMotionNext) == 0;
    int steer = motion && LoaderHook("vehicle boxes: the steering pass", game + VB_STEER, (void*)VbSteer, (void**)&g_vbSteerNext) == 0;
    int box = steer && LoaderHook("vehicle boxes: the box", exe + VB_BOX, (void*)VbBox, (void**)&g_vbBoxNext) == 0;
    if (box)
    {
        Note("performance fix vehicle-box: installed; each vehicle's box is computed once per motion and steering pass");
        return 1;
    }
    if (steer) HookRemove(NULL, game + VB_STEER, (void*)VbSteer);
    if (motion) HookRemove(NULL, game + VB_MOTION, (void*)VbMotion);
    Note("performance fix vehicle-box: not installed; a function could not be hooked");
    return 0;
}

/* 1 installed, -1 not, 0 not yet: code still being decoded gets until lastTry. */
static int VehicleBoxTry(uintptr_t exe, uintptr_t game, int lastTry)
{
    if (!VbPinned(exe, game))
    {
        if (!lastTry) return 0;
        Note("performance fix vehicle-box: not installed; the code is not the reviewed one");
        return -1;
    }
    if (!PerfFixOn("vehicle-box")) return -1;
    return VehicleBoxInstallAt(exe, game) ? 1 : -1;
}

/* After the game loaded (WatchStats). A minute later the code never will be the reviewed one. */
static void VehicleBoxWatch(void)
{
    if (g_vbState != 0) return;
    if (strcmp(g_build, "25480438"))
    {
        g_vbState = -1;
        Note("performance fix vehicle-box: not installed; build %s is not the reviewed 25480438", g_build);
        return;
    }
    if (g_vbFirstTry == 0) g_vbFirstTry = GetTickCount64();
    g_vbState = VehicleBoxTry((uintptr_t)GetModuleHandleW(NULL), ApiModuleBase("game.dll", NULL), GetTickCount64() - g_vbFirstTry >= 60000);
}
