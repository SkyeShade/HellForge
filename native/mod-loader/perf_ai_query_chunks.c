typedef uint64_t (*AqTaskFn)(void* shed, void* task, void* channel, uint32_t* row);
typedef uint32_t (*AqRunJobFn)(void* fn, uint32_t** rows, const char* name, uint32_t p4, int32_t priority, uint32_t count, void* p7);
typedef void (*AqJoinFn)(void* entities);

typedef struct AqBatch
{
    const char* name;
    uint32_t rva;
    uintptr_t fn;            /* game + rva */
    void* volatile next;
    uint32_t* rows[AQ_ROWS_MAX];
    uint32_t rowCount, end, chunk;
    volatile LONG cursor;
    volatile LONG active;    /* 1 from its kick to the join's end */
} AqBatch;

static AqBatch g_aq[AQ_BATCHES] = {
    {"raycast", 0x175C5C0u}, {"navmesh raycast", 0x175CD40u}, {"overlap", 0x175B800u}, {"edge gather", 0x134A530u},
};
static void* volatile g_aqRunNext;
static void* volatile g_aqJoinNext;
static volatile LONG g_aqOn;
static int g_aqState;          /* 0 waiting for the code, 1 installed, -1 not */
static ULONGLONG g_aqFirstTry, g_aqReportedAt;
static LONG64 g_aqJoinTicks, g_aqStealTicks, g_aqJoins; /* the game thread's */
static volatile LONG64 g_aqChunks, g_aqStolen;
static LONG64 g_aqLast[5];     /* the watch thread's: the counts at its last report */
static volatile LONG g_aqLeft; /* kicks left to the game */

/* The first pin that differs, or NULL. */
static const char* AiQueryChunksMismatch(uintptr_t exe, uintptr_t game)
{
    if (EdgeBatchMismatch(game) != NULL) return "the edge batch's code"; /* the edge gather task, its kick and the join's wait */
    for (size_t i = 0; i < AQ_GAME_PINS; i++)
        if (!PinMatches(game + kAqGamePins[i].rva, kAqGamePins[i].bytes, kAqGamePins[i].size)) return kAqGamePins[i].what;
    for (size_t i = 0; i < AQ_EXE_PINS; i++)
        if (!PinMatches(exe + kAqExePins[i].rva, kAqExePins[i].bytes, kAqExePins[i].size)) return kAqExePins[i].what;
    return NULL;
}

/* The batch's chunks until the cursor passes its end; stolen: the game thread's, in the join. */
static void AiQueryChunksRun(AqBatch* b, void* shed, void* task, void* channel, int stolen)
{
    AqTaskFn next = (AqTaskFn)b->next;
    uint32_t end = b->end, chunk = b->chunk;
    for (;;)
    {
        uint32_t start = (uint32_t)InterlockedExchangeAdd(&b->cursor, (LONG)chunk);
        if (start >= end) return;
        uint32_t row[3] = {start, end - start > chunk ? start + chunk : end, 0};
        next(shed, task, channel, row);
        InterlockedIncrement64(stolen ? &g_aqStolen : &g_aqChunks);
    }
}

/* A task of a batch: its row from this kick takes chunks, then is done; anything else runs as the game's. */
static uint64_t AiQueryChunksTask(AqBatch* b, void* shed, void* task, void* channel, uint32_t* row)
{
    int own = 0;
    if (b->active)
        for (uint32_t i = 0; i < b->rowCount && !own; i++) own = b->rows[i] == row;
    if (!own) return ((AqTaskFn)b->next)(shed, task, channel, row);
    AiQueryChunksRun(b, shed, task, channel, 0);
    MemoryBarrier();
    ((volatile uint32_t*)row)[2] = 1;
    return 0;
}

static uint64_t AiQueryChunksTask0(void* s, void* t, void* c, uint32_t* row) { return AiQueryChunksTask(&g_aq[0], s, t, c, row); }
static uint64_t AiQueryChunksTask1(void* s, void* t, void* c, uint32_t* row) { return AiQueryChunksTask(&g_aq[1], s, t, c, row); }
static uint64_t AiQueryChunksTask2(void* s, void* t, void* c, uint32_t* row) { return AiQueryChunksTask(&g_aq[2], s, t, c, row); }
static uint64_t AiQueryChunksTask3(void* s, void* t, void* c, uint32_t* row) { return AiQueryChunksTask(&g_aq[3], s, t, c, row); }
static void* const kAqTasks[AQ_BATCHES] = {(void*)AiQueryChunksTask0, (void*)AiQueryChunksTask1, (void*)AiQueryChunksTask2,
    (void*)AiQueryChunksTask3};

/* A kick, on the game thread before its tasks exist: the rows must run from their first start to the last end, none
 * done yet. A batch still active was never joined: its kick is left to the game, as is one with other rows. */
static void AiQueryChunksKick(AqBatch* b, uint32_t** rows, uint32_t count)
{
    if (b->active) { InterlockedExchange(&b->active, 0); InterlockedIncrement(&g_aqLeft); return; }
    uint32_t first = rows[0][0], end = first;
    for (uint32_t i = 0; i < count; i++)
    {
        if (rows[i][0] != end || rows[i][1] < rows[i][0] || rows[i][2] != 0) { InterlockedIncrement(&g_aqLeft); return; }
        end = rows[i][1];
        b->rows[i] = rows[i];
    }
    uint32_t pieces = count * AQ_SPLIT;
    b->rowCount = count;
    b->end = end;
    b->chunk = (end - first + pieces - 1) / pieces;
    if (b->chunk == 0) b->chunk = 1;
    b->cursor = (LONG)first;
    MemoryBarrier();
    InterlockedExchange(&b->active, 1);
}

static uint32_t AiQueryChunksRunJob(void* fn, uint32_t** rows, const char* name, uint32_t p4, int32_t priority, uint32_t count, void* p7)
{
    if (g_aqOn && rows != NULL && count != 0 && count <= AQ_ROWS_MAX)
        for (int i = 0; i < AQ_BATCHES; i++)
            if ((uintptr_t)fn == g_aq[i].fn) { AiQueryChunksKick(&g_aq[i], rows, count); break; }
    return ((AqRunJobFn)g_aqRunNext)(fn, rows, name, p4, priority, count, p7);
}

/* The join on the game thread: chunks still left are its own, then the game's wait for the tasks still running; after
 * it no task of these kicks is left. */
static void AiQueryChunksJoin(void* entities)
{
    LARGE_INTEGER t0, t1, t2;
    QueryPerformanceCounter(&t0);
    if (g_aqOn)
        for (int i = 0; i < AQ_BATCHES; i++)
            if (g_aq[i].active) AiQueryChunksRun(&g_aq[i], NULL, NULL, NULL, 1);
    QueryPerformanceCounter(&t1);
    ((AqJoinFn)g_aqJoinNext)(entities);
    QueryPerformanceCounter(&t2);
    for (int i = 0; i < AQ_BATCHES; i++) InterlockedExchange(&g_aq[i].active, 0);
    g_aqStealTicks += t1.QuadPart - t0.QuadPart;
    g_aqJoinTicks += t2.QuadPart - t0.QuadPart;
    g_aqJoins++;
}

/* Every hook or none: the tasks first, then the join, the job runner last, and only then on. */
static int AiQueryChunksInstallAt(uintptr_t exe, uintptr_t game)
{
    int hooked = 0;
    for (; hooked < AQ_BATCHES; hooked++)
    {
        g_aq[hooked].fn = game + g_aq[hooked].rva;
        if (LoaderHook("ai-query-chunks: a query task", g_aq[hooked].fn, kAqTasks[hooked], (void**)&g_aq[hooked].next) != 0) break;
    }
    int join = hooked == AQ_BATCHES && LoaderHook("ai-query-chunks: the join", game + AQ_JOIN, (void*)AiQueryChunksJoin, (void**)&g_aqJoinNext) == 0;
    int run = join && LoaderHook("ai-query-chunks: the job runner", exe + AQ_RUN_JOB, (void*)AiQueryChunksRunJob, (void**)&g_aqRunNext) == 0;
    if (run)
    {
        g_aqReportedAt = GetTickCount64();
        InterlockedExchange(&g_aqOn, 1);
        Note("performance fix ai-query-chunks: installed; the AI's raycast, navmesh raycast, overlap and edge gather tasks take their batch "
            "in chunks of a %uth of a share, and the game thread runs chunks itself before it waits", AQ_SPLIT);
        return 1;
    }
    if (join) HookRemove(NULL, game + AQ_JOIN, (void*)AiQueryChunksJoin);
    while (hooked-- > 0) HookRemove(NULL, g_aq[hooked].fn, kAqTasks[hooked]);
    Note("performance fix ai-query-chunks: not installed; a function could not be hooked");
    return 0;
}

/* 1 installed, -1 not, 0 not yet: code still being decoded gets until lastTry. */
static int AiQueryChunksTry(uintptr_t exe, uintptr_t game, int lastTry)
{
    const char* differs = AiQueryChunksMismatch(exe, game);
    if (differs != NULL)
    {
        if (!lastTry) return 0;
        Note("performance fix ai-query-chunks: not installed; %s is not the reviewed code", differs);
        return -1;
    }
    if (!PerfFixOn("ai-query-chunks")) return -1;
    return AiQueryChunksInstallAt(exe, game) ? 1 : -1;
}

/* After the game loaded (WatchStats). A minute later the code never will be the reviewed one. */
static void AiQueryChunksWatch(void)
{
    if (g_aqState == 1 && g_aqJoins > g_aqLast[0] && GetTickCount64() - g_aqReportedAt >= 60000)
    {
        LARGE_INTEGER hz;
        QueryPerformanceFrequency(&hz);
        LONG64 now[5] = {g_aqJoins, g_aqJoinTicks, g_aqStealTicks, g_aqChunks, g_aqStolen};
        double joins = (double)(now[0] - g_aqLast[0]), ms = 1e3 / (double)hz.QuadPart;
        LONG64 chunks = now[3] - g_aqLast[3] + now[4] - g_aqLast[4];
        Note("performance fix ai-query-chunks: in the last %.0f s, %.0f joins took %.3f ms each on the game thread (%.3f ms of it running "
            "chunks); %lld chunks, %.1f%% by the game thread; %ld kick(s) left to the game so far",
            (double)(GetTickCount64() - g_aqReportedAt) / 1e3, joins, (double)(now[1] - g_aqLast[1]) * ms / joins,
            (double)(now[2] - g_aqLast[2]) * ms / joins, (long long)chunks,
            chunks ? 100.0 * (double)(now[4] - g_aqLast[4]) / (double)chunks : 0.0, (long)g_aqLeft);
        memcpy(g_aqLast, now, sizeof now);
        g_aqReportedAt = GetTickCount64();
    }
    if (g_aqState != 0) return;
    if (strcmp(g_build, "25480438"))
    {
        g_aqState = -1;
        Note("performance fix ai-query-chunks: not installed; build %s is not the reviewed 25480438", g_build);
        return;
    }
    uintptr_t game = ApiModuleBase("game.dll", NULL);
    if (game == 0) return;
    if (g_aqFirstTry == 0) g_aqFirstTry = GetTickCount64();
    g_aqState = AiQueryChunksTry((uintptr_t)GetModuleHandleW(NULL), game, GetTickCount64() - g_aqFirstTry >= 60000);
}
