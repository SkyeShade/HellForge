#define MG_PINS (sizeof kMgPins / sizeof kMgPins[0])

typedef void (*MgInitFn)(uintptr_t grid, float cell);
typedef struct MgGrid { uintptr_t grid; uint8_t* slots; uint8_t* entries; } MgGrid;

static void* volatile g_mgNext;
static MgGrid g_mgGrids[MG_MAX]; /* the game thread's: worlds are set up there */
static int g_mgGridCount;
static int g_mgState;            /* 0 waiting for the code, 1 installed, -1 not */
static ULONGLONG g_mgFirstTry;
static volatile LONG g_mgEnlarged, g_mgEnlargedReported, g_mgRefused, g_mgRefusedReported;

/* The first pin that differs, or NULL. */
static const char* MotionGridMismatch(uintptr_t game)
{
    for (size_t i = 0; i < MG_PINS; i++)
        if (!PinMatches(game + kMgPins[i].rva, kMgPins[i].bytes, kMgPins[i].size)) return kMgPins[i].what;
    return NULL;
}

/* 1 when the header is the game's fresh one: its inline slots and entries, 256 of each, nothing handed out. */
static int MotionGridFresh(uintptr_t grid)
{
    return *(uintptr_t*)(grid + MG_SLOTS_AT) == grid + 0x800u && *(uint32_t*)(grid + MG_COUNT_AT) == MG_GAME_COUNT &&
        *(uintptr_t*)(grid + MG_ENTRIES_AT) == grid + 0x1000u && *(int32_t*)(grid + MG_EMPTY_AT) == -1 &&
        *(uint32_t*)(grid + MG_STEP_AT) == 2u && *(uint32_t*)(grid + MG_CURSOR_AT) == 0u;
}

/* This grid's arrays (kept per address: the same grid is set up again for every world), or NULL. */
static MgGrid* MotionGridArrays(uintptr_t grid)
{
    for (int i = 0; i < g_mgGridCount; i++) if (g_mgGrids[i].grid == grid) return &g_mgGrids[i];
    if (g_mgGridCount == MG_MAX) return NULL;
    uint8_t* slots = (uint8_t*)VirtualAlloc(NULL, (size_t)MG_COUNT * (8u + MG_ENTRY), MEM_RESERVE | MEM_COMMIT, PAGE_READWRITE);
    if (slots == NULL) return NULL;
    MgGrid* g = &g_mgGrids[g_mgGridCount++];
    g->grid = grid;
    g->slots = slots;
    g->entries = slots + (size_t)MG_COUNT * 8u;
    return g;
}

/* After the game's set-up of `grid`: our slots and entries, empty as the game's set-up leaves its own. The inline slots
 * and entries become per-entry blocks: zeroed, since the clip reads a block's +4 as an edge query index (the game's
 * slot keys there, -1, sent it 4 billion queries past the batch). */
static void MotionGridEnlarge(uintptr_t grid)
{
    if (!MotionGridFresh(grid)) { InterlockedIncrement(&g_mgRefused); return; }
    MgGrid* g = MotionGridArrays(grid);
    if (g == NULL) { InterlockedIncrement(&g_mgRefused); return; }
    for (uint32_t i = 0; i < MG_COUNT; i++)
    {
        uint32_t* slot = (uint32_t*)(g->slots + (size_t)i * 8u);
        slot[0] = 0xFFFFFFFFu;
        slot[1] = 0;
        uint8_t* e = g->entries + (size_t)i * MG_ENTRY;
        memset(e, 0, MG_ENTRY);
        *(uint32_t*)(e + 0xC) = i < MG_RADII ? 0xFFFFFFFFu : MG_TAKEN;
    }
    memset((void*)(grid + MG_GAME_COUNT * 8u), 0, MG_SLOTS_AT - MG_GAME_COUNT * 8u);
    *(uintptr_t*)(grid + MG_SLOTS_AT) = (uintptr_t)g->slots;
    *(uintptr_t*)(grid + MG_ENTRIES_AT) = (uintptr_t)g->entries;
    *(uint32_t*)(grid + MG_COUNT_AT) = MG_COUNT;
    InterlockedIncrement(&g_mgEnlarged);
}

/* The set-up, on the game thread while a world is made. */
static void MotionGridInit(uintptr_t grid, float cell)
{
    ((MgInitFn)g_mgNext)(grid, cell);
    MotionGridEnlarge(grid);
}

/* 1 installed, -1 not, 0 not yet: code still being decoded gets until lastTry. */
static int MotionGridTry(uintptr_t game, int lastTry)
{
    const char* differs = MotionGridMismatch(game);
    if (differs != NULL)
    {
        if (!lastTry) return 0;
        Note("performance fix motion-grid: not installed; %s is not the reviewed code", differs);
        return -1;
    }
    if (!PerfFixOn("motion-grid")) return -1;
    if (LoaderHook("motion-grid: the grid's set-up", game + MG_INIT, (void*)MotionGridInit, (void**)&g_mgNext) != 0)
    {
        Note("performance fix motion-grid: not installed; the grid's set-up could not be hooked");
        return -1;
    }
    Note("performance fix motion-grid: installed; motion grids set up from now on hold %u moving agents in %u slots (the game's %u)",
        MG_RADII, MG_COUNT, MG_GAME_COUNT);
    return 1;
}

/* After the game loaded (WatchStats). A minute later the code never will be the reviewed one. */
static void MotionGridWatch(void)
{
    if (g_mgState == 1 && (g_mgEnlarged != g_mgEnlargedReported || g_mgRefused != g_mgRefusedReported))
    {
        g_mgEnlargedReported = g_mgEnlarged;
        g_mgRefusedReported = g_mgRefused;
        Note("performance fix motion-grid: %ld grid set-up(s) made larger so far%s", (long)g_mgEnlargedReported,
            g_mgRefusedReported ? "; some were not the game's fresh set-up, or past our room, and stayed as they were" : "");
    }
    if (g_mgState != 0) return;
    if (strcmp(g_build, "25480438"))
    {
        g_mgState = -1;
        Note("performance fix motion-grid: not installed; build %s is not the reviewed 25480438", g_build);
        return;
    }
    uintptr_t game = ApiModuleBase("game.dll", NULL);
    if (game == 0) return;
    if (g_mgFirstTry == 0) g_mgFirstTry = GetTickCount64();
    g_mgState = MotionGridTry(game, GetTickCount64() - g_mgFirstTry >= 60000);
}
