// HellForge stand-in for PartyWin.dll (PlayFab Party 1.10.16). The stand-in plays the Party service: a network created here
// can be connected to and hosted, with local users, endpoints and invitations behaving as the SDK documents. With
// %HELLFORGE_PIPE% set, the local HellForge backend (src/HellForge.LocalBackend/Multiplayer/PartyService.cs) connects networks between
// friends: a network hosted here is announced to it, a friend's network is joined through it, friends' machines and
// endpoints appear as remote devices and endpoints, and the game's messages travel endpoint to endpoint through the
// backends. Without it, a friend's network fails to connect the way the real library does offline. HD2 exits when a
// hosting call fails synchronously, so every network operation is accepted and completes through state changes
// (stand-in boots, 2026-10-14). The host's PartyNetworkKickDevice and PartyNetworkKickUser go to the backend as a kick of
// that machine from the host's lobby (party.kick; LobbyService.Kick), which also takes it out of the network. Every
// export not defined here is a logged stub generated by HellForge.SdkShimGen. Nothing here can reach PlayFab or Azure
// relays.
