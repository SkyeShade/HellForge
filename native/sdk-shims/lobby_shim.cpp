// HellForge stand-in for PlayFabMultiplayerWin.dll (PlayFab Multiplayer 1.8.7: lobbies and matchmaking). Every operation is
// accepted at once and completed through the documented state changes (HD2 exits when its hosting path fails
// synchronously). With %HELLFORGE_PIPE% set, the local HellForge backend's lobby service is the authority (link.h,
// src/HellForge.LocalBackend/Multiplayer/LobbyService.cs): requests go to it, a friend's lobby is reached through it, and this
// library mirrors the lobbies from its events. Without it, the stand-in plays the Lobby service for this machine only,
// and joining a friend's lobby fails. A lobby search (the Galactic Map) goes to the backend, which answers it from the
// lobby directory (DirectoryService.cs); without it a search finds nothing. Through the backend the owner's
// PFLobbyForceRemoveMember kicks a member (the backend refuses them for the lobby's lifetime), and PFLobbySendInvite
// invites someone: the lobby's owner admits them whatever its privacy, and a friend invited gets InviteReceived while
// listening. Matchmaking and the remaining exports are logged stubs generated by HellForge.SdkShimGen. Nothing here can
// reach PlayFab.
