/* The Steam bridge wire protocol (docs/steam-bridge.md): pipe messages and the callback ring, shared between the broker
 * (hellforge_steam_broker.exe, normal integrity) and the game's stand-in (steam_api64.dll, low integrity). */
#pragma once
#include <stdint.h>

/* --- Pipe messages (message-mode named pipe, one WriteFile per message) ---
 *
 * Each message: [uint32 type][body...], where the body's length is the pipe message's size minus 4. The pipe is in
 * message mode, so ReadFile returns one whole message. */

enum {
    BRIDGE_HELLO        = 1,  /* client -> broker: uint32 pid */
    BRIDGE_HELLO_OK     = 2,  /* broker -> client: uint64 ring section handle, already duplicated into the client */
    BRIDGE_HELLO_DENIED = 3,  /* broker -> client: empty, then the broker disconnects and waits for the next client */
    BRIDGE_CALL         = 4,  /* client -> broker: uint32 seq, uint32 function, then argument bytes */
    BRIDGE_RESULT       = 5,  /* broker -> client: uint32 seq (the call's), uint32 status, then result bytes */
    BRIDGE_SHUTDOWN     = 6,  /* client -> broker */
};

/* Functions a BRIDGE_CALL names. The interface methods the allow-list lets through are numbered from
 * BRIDGE_FN_METHODS (bridge_gen.h, generated by SdkShimGen steam-bridge). */
enum {
    BRIDGE_FN_IS_STEAM_RUNNING = 0,  /* result: uint8 */
    BRIDGE_FN_METHODS          = 100,
};

/* A BRIDGE_RESULT's status. */
enum {
    BRIDGE_STATUS_OK        = 0,
    BRIDGE_STATUS_UNKNOWN   = 1,  /* no such function, or refused by the allow-list */
    BRIDGE_STATUS_MALFORMED = 2,  /* too short, or larger than BRIDGE_MSG_BUF */
    BRIDGE_STATUS_REFUSED   = 3,  /* the allow-list's checks refused the arguments (the broker logs why) */
};

/* --- Callback ring (shared memory, single-producer single-consumer) ---
 *
 * The broker writes callbacks; the game reads them in RunCallbacks. An idle frame reads writeSeq only (no system call).
 * Fixed-size slots: the largest callback the game registers is 712 bytes (SteamNetConnectionStatusChanged).
 *
 * The game can write the whole mapping, so neither side indexes with a value the other wrote without bounding it: each
 * keeps its own sequence privately and only publishes it here, and a slot index is always seq % BRIDGE_RING_SLOT_COUNT
 * of an unsigned sequence. */

#define BRIDGE_RING_SLOT_SIZE   1024
#define BRIDGE_RING_SLOT_COUNT  60u
#define BRIDGE_RING_DATA_SIZE   (BRIDGE_RING_SLOT_SIZE - 8)

typedef struct BridgeRingSlot {
    uint32_t callbackId;
    uint32_t dataSize;
    uint8_t  data[BRIDGE_RING_DATA_SIZE];
} BridgeRingSlot;

typedef struct BridgeRingHeader {
    volatile uint64_t writeSeq;  /* published by the broker */
    uint8_t _pad1[56];
    volatile uint64_t readSeq;   /* published by the game */
    uint8_t _pad2[56];
} BridgeRingHeader;

/* A call result in the ring: callbackId carries this flag, and the data starts with the call's uint64 handle and a
 * uint8 I/O failure flag (then 7 bytes of padding), before the result struct. */
#define BRIDGE_CALL_RESULT_FLAG 0x80000000u
#define BRIDGE_CALL_RESULT_HEADER 16u

/* A Steam P2P packet the broker read for the game, from one of its co-op peers: callbackId BRIDGE_P2P_PACKET (no Steam
 * callback has it), data a BridgeP2PPiece then that piece of the packet. A packet larger than one slot comes in pieces,
 * in order, each saying where it starts; a packet is at most BRIDGE_P2P_MAX bytes. */
#define BRIDGE_P2P_PACKET 0x40000001u
#define BRIDGE_P2P_MAX 8192u
typedef struct BridgeP2PPiece {
    uint64_t remote;    /* the sender's SteamID */
    int32_t  channel;
    uint32_t total;     /* the packet's size */
    uint32_t offset;    /* where this piece starts in it */
    uint32_t pad;
} BridgeP2PPiece;
#define BRIDGE_P2P_PIECE (BRIDGE_RING_DATA_SIZE - (uint32_t)sizeof(BridgeP2PPiece))

/* --- The snapshot (after the ring in the same section) ---
 *
 * What the game asks of Steam every frame, answered without a round trip: the broker fills it at init and refreshes it
 * about once a second. A seqlock: the broker makes version odd, writes, then makes it even again; the game copies what it
 * needs and retries if version changed or was odd. The game can write the mapping, so the broker never reads it back. */

#define BRIDGE_DLC_MAX 64

typedef struct BridgeSnapshotDlc {
    uint32_t appId;
    uint8_t  available;
    uint8_t  subscribed;
    uint8_t  _pad[2];
    char     name[128];
} BridgeSnapshotDlc;

typedef struct BridgeSnapshot {
    volatile uint32_t version;
    uint32_t ready;         /* nonzero once the broker filled it the first time */
    uint64_t steamId;
    uint8_t  loggedOn;
    uint8_t  steamDeck;
    uint8_t  hasBeta;
    uint8_t  _pad;
    uint32_t dlcCount;      /* at most BRIDGE_DLC_MAX */
    char     personaName[128];
    char     language[32];
    char     ipCountry[8];
    char     betaName[64];
    BridgeSnapshotDlc dlc[BRIDGE_DLC_MAX];
} BridgeSnapshot;

#define BRIDGE_RING_MAP_SIZE (sizeof(BridgeRingHeader) + (BRIDGE_RING_SLOT_COUNT) * sizeof(BridgeRingSlot) + sizeof(BridgeSnapshot))

static inline BridgeSnapshot* BridgeSnapshotOf(BridgeRingHeader* ring)
{
    return (BridgeSnapshot*)((uint8_t*)(ring + 1) + (size_t)BRIDGE_RING_SLOT_COUNT * sizeof(BridgeRingSlot));
}

static inline BridgeRingSlot* BridgeRingSlotAt(BridgeRingHeader* ring, uint64_t seq)
{
    return (BridgeRingSlot*)((uint8_t*)(ring + 1) + (size_t)(seq % BRIDGE_RING_SLOT_COUNT) * sizeof(BridgeRingSlot));
}

/* The game's published read position as the broker may use it: never past what the broker wrote, never more than a
 * ring behind it. */
static inline uint64_t BridgeRingClampRead(uint64_t published, uint64_t written)
{
    if (published > written) return written;
    if (written - published > BRIDGE_RING_SLOT_COUNT) return written - BRIDGE_RING_SLOT_COUNT;
    return published;
}
